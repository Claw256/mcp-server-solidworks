"""Glue between the planner's typed questions and the MCP tools that put them to the user.

Questions are generated by `drawing.build_questions`; this module renders them for the model, parses
the answers that come back, and remembers the last open set so `ask_user` can take just ids.
In-memory only: a question set is cheap to regenerate from the drawing, so nothing here is state that
must survive a restart.
"""
import json

# {question_id: question} for the most recent analyze_drawing that left questions open.
PENDING: dict = {}
PENDING_SOURCE: dict = {"file": None}


def remember(file_path: str, questions: list) -> None:
    PENDING.clear()
    PENDING.update({q["id"]: q for q in questions})
    PENDING_SOURCE["file"] = file_path


def parse_answers(raw: str):
    """-> (dict, error). '' -> ({}, None). Values are coerced to str (questions.apply_answers parses)."""
    if not raw or not raw.strip():
        return {}, None
    try:
        obj = json.loads(raw)
    except ValueError as ex:
        return {}, f"answers must be a JSON object like {{\"bend_1\": \"l:5\"}}: {ex}"
    if not isinstance(obj, dict):
        return {}, "answers must be a JSON object mapping question id -> value"
    return {str(k): str(v) for k, v in obj.items()}, None


def render(questions: list, file_path: str) -> str:
    """The model-facing block: what to ask, with the evidence, the options and the default."""
    if not questions:
        return ""
    blocking = sum(1 for q in questions if q["blocking"])
    lines = [f"OPEN QUESTIONS ({len(questions)}, {blocking} blocking) — put these to the user (ask_user, or in "
             f"chat with the options and default), then re-call analyze_drawing with "
             f"answers='{{\"<id>\": \"<value>\"}}'. accept_defaults=true only if the user said to use the defaults."]
    for q in questions:
        flag = "blocking" if q["blocking"] else "assumption"
        default = f", default: {q['default']}" if q.get("default") is not None else ", no default"
        lines.append(f"  [{q['id']}] ({flag}{default}) {q['prompt']}")
        for o in q["options"]:
            ev = f" — {o['evidence']}" if o.get("evidence") else ""
            lines.append(f"      {o['value']} = {o['label']}{ev}")
    return "\n".join(lines)


def render_ledger(ledger: list) -> str:
    if not ledger:
        return ""
    rows = []
    for e in ledger:
        note = f" ({e['note']})" if e.get("note") else ""
        rows.append(f"  {e['field']} = {e['value']}  [{e['source']}]{note}")
    return "ASSUMPTIONS LEDGER — every value the build rests on that is not a plain drawing read:\n" + "\n".join(rows)
