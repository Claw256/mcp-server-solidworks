"""Contract test (P0.3): the MCP adapter (server.py) vs the execution contract.

Guards against drift between the model-facing MCP surface generated by the MCP SDK
from `server.py` and the hand-maintained low-level tool contract at
`execution/solidworks/contracts/tool-schemas.json`. If a tool or a parameter is
added/removed/renamed on one side but not the other, this test fails.

Scope: structural drift only — the SET of tools, and the SET of parameter names
per tool. (The contract stores prose-valued params, not machine types, so deeper
type/enum checks would be brittle; those live in server.py's Literal/Field
constraints, exercised by the live smoke test.)

SECOND CHECK (2026-07-30, ADR-069): the RESOURCE surface. The recipe moved from the
`get_recipe` tool to `recipe://usage/*` + `schema://*` resources, and the only thing telling
the model those URIs exist is prose inside other tools' docstrings. So a renamed URI whose
docstring pointer is not updated does not fail loudly — the model just silently stops finding
the rules. `find_resource_drift` closes exactly that hole: every URI mentioned anywhere in
server.py must resolve, every declared section must be registered AND present in
recipe-usage.md. Resources have no `tool-schemas.json` counterpart (that file's every top-level
key is a tool), so the declared surface is `_recipes._RECIPE_SECTIONS` itself.

Runnable two ways:
  - standalone:  python tests/test_schema_contract.py   (exits non-zero on drift)
  - pytest:      pytest tests/test_schema_contract.py
"""
import asyncio
import json
import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ADAPTER_DIR = os.path.dirname(_HERE)
_REPO_ROOT = os.path.dirname(os.path.dirname(_ADAPTER_DIR))
_CONTRACT_PATH = os.path.join(
    _REPO_ROOT, "execution", "solidworks", "contracts", "tool-schemas.json"
)

# Import server.py as a module (it lives one dir up from tests/).
sys.path.insert(0, _ADAPTER_DIR)
import server  # noqa: E402
from solidpilot.tools import recipes as _recipes  # noqa: E402
from solidpilot.tools import drawing_in as _drawing_in  # noqa: E402


def _adapter_source() -> str:
    """server.py plus every solidpilot module: the tool surface now lives across them."""
    parts = []
    for root, _dirs, files in os.walk(os.path.join(_ADAPTER_DIR, "solidpilot")):
        for name in sorted(files):
            if name.endswith(".py"):
                with open(os.path.join(root, name), encoding="utf-8") as fh:
                    parts.append(fh.read())
    with open(os.path.join(_ADAPTER_DIR, "server.py"), encoding="utf-8") as fh:
        parts.append(fh.read())
    return "\n".join(parts)


def _adapter_tools():
    """{tool_name: set(param_names)} from the SDK-generated schema."""
    tools = asyncio.run(server.mcp.list_tools())
    out = {}
    for t in tools:
        props = (t.input_schema or {}).get("properties", {})
        out[t.name] = set(props.keys())
    return out


def _contract_tools():
    """{tool_name: set(param_names)} from tool-schemas.json (params sub-dict)."""
    with open(_CONTRACT_PATH, encoding="utf-8") as fh:
        contract = json.load(fh)
    out = {}
    for name, spec in contract.items():
        params = (spec.get("input") or {}).get("params") or {}
        out[name] = set(params.keys())
    return out


def find_drift():
    """Return a list of human-readable drift messages (empty == in sync)."""
    adapter = _adapter_tools()
    contract = {k: v for k, v in _contract_tools().items() if k not in EXECUTION_ONLY_TOOLS}
    errors = []

    only_adapter = sorted(set(adapter) - set(contract))
    only_contract = sorted(set(contract) - set(adapter))
    for name in only_adapter:
        errors.append(f"tool '{name}' is exposed by server.py but missing from tool-schemas.json")
    for name in only_contract:
        errors.append(f"tool '{name}' is in tool-schemas.json but not exposed by server.py")

    for name in sorted(set(adapter) & set(contract)):
        a, c = adapter[name], contract[name]
        missing_in_contract = sorted(a - c)
        missing_in_adapter = sorted(c - a)
        if missing_in_contract:
            errors.append(f"tool '{name}': params {missing_in_contract} in server.py but not in tool-schemas.json")
        if missing_in_adapter:
            errors.append(f"tool '{name}': params {missing_in_adapter} in tool-schemas.json but not in server.py")
    return errors


def find_resource_drift():
    """Return drift messages for the RESOURCE surface (empty == in sync)."""
    errors = []
    static = {str(r.uri) for r in asyncio.run(server.mcp.list_resources())}
    templates = [t.uri_template for t in asyncio.run(server.mcp.list_resource_templates())]
    _header, sections = _recipes._recipe_sections()

    # 1. Every declared section is registered AND actually exists in recipe-usage.md.
    for slug in _recipes._RECIPE_SECTIONS:
        if f"recipe://usage/{slug}" not in static:
            errors.append(f"section '{slug}' is in _RECIPE_SECTIONS but not registered as a resource")
        if slug not in sections:
            errors.append(f"section '{slug}' is served but has no '## {slug} — ...' header in "
                          f"recipe-usage.md")

    # 2. A section present in the file but not served — deliberate (the surface is
    #    user-controlled), so report it as INFO-level drift only if it is never mentioned.
    unserved = sorted(set(sections) - set(_recipes._RECIPE_SECTIONS))
    if unserved:
        errors.append(f"recipe-usage.md has section(s) {unserved} that are NOT served — add them "
                      f"to _RECIPE_SECTIONS deliberately, or drop the header")

    # 3. THE IMPORTANT ONE: every recipe://|schema:// URI mentioned anywhere in server.py must
    #    resolve, or the docstring pointers silently stop finding the rules.
    source = _adapter_source()
    mentioned = set(re.findall(r"(?:recipe|schema)://[A-Za-z0-9_./{}-]+", source))
    prefixes = [t.split("{")[0] for t in templates if "{" in t]
    for uri in sorted(mentioned):
        if uri in static:
            continue
        # A braced URI is either the template's own registration or an f-string placeholder
        # (`f"recipe://usage/{slug}"`); both are satisfied by a template with the same literal
        # prefix, while a typo'd scheme/path still fails.
        base = uri.split("{")[0] if "{" in uri else uri.rstrip("/")
        if not any(p and base.startswith(p.rstrip("/")) for p in prefixes):
            errors.append(f"URI '{uri}' is mentioned in server.py but resolves to no resource "
                          f"or template")
    return errors


def find_drawing_api_drift():
    """Every `_draw.<name>` server.py calls must actually be exported by the drawing package.

    The same silent-failure class as the resource URIs (ADR-069): the adapter reaches into
    `cad-planner/drawing` through a package `__all__`, and a helper added to a MODULE but not
    re-exported from `__init__.py` still imports fine, still passes every offline gate, and then
    fails only on a live MCP call with `module 'drawing' has no attribute ...`. That is exactly
    how `view_records` shipped broken (2026-09-03) -- caught by a live call, not by a gate, and it
    cost the user a reconnect. Cheap to check, so check it.
    """
    errors = []
    src = _adapter_source()
    used = set(re.findall(r"_draw\.([A-Za-z_][A-Za-z0-9_]*)", src))
    if _drawing_in._draw is None:
        return ["the drawing package did not import — cannot verify the _draw API surface"]
    exported = set(getattr(_drawing_in._draw, "__all__", []))
    for name in sorted(used):
        if not hasattr(_drawing_in._draw, name):
            errors.append(f"server.py calls _draw.{name}, which the drawing package does not "
                          f"provide at all")
        elif exported and name not in exported:
            errors.append(f"server.py calls _draw.{name}, which resolves but is NOT in the "
                          f"drawing package's __all__ — add it to cad-planner/drawing/__init__.py")
    return errors


# Tools that exist ONLY in the execution layer (no model-facing adapter tool); the adapter reaches them
# through bridge._call_raw. Adding to this set is a deliberate decision.
EXECUTION_ONLY_TOOLS = {"save_copy", "feature_tree", "truncate_feature_tree"}


# Tools that exist ONLY in the adapter (no C# handler). Adding to this set is a deliberate decision.
ADAPTER_ONLY_TOOLS = {
    "analyze_drawing", "annotate_regions", "ask_user", "compare_assemblies", "compare_parts", "ensure_ready",
    "get_recipe", "prepare_drawing", "rebuild_from_ir", "save_analysis", "design_new", "design_step",
    "design_undo", "design_redo", "design_history",
    "verify_against_interpretation", "replay_run", "job_status", "checkpoint", "analyze_mesh",
}


def _csharp_tools():
    """Tool names declared with [Tool("...")] on the C# service (source scan: no build needed)."""
    root = os.path.join(_REPO_ROOT, "execution", "solidworks", "SolidworksExecution", "Services")
    names = set()
    for fn in os.listdir(root):
        if fn.endswith(".cs"):
            with open(os.path.join(root, fn), encoding="utf-8-sig") as fh:
                names |= set(re.findall(r'\[Tool\("(\w+)"', fh.read()))
    return names


def find_csharp_drift():
    """The C# registry, the adapter and tool-schemas.json must describe the same tool set."""
    cs, adapter, contract = _csharp_tools(), set(_adapter_tools()), set(_contract_tools())
    errors = []
    if not cs:
        return ["no [Tool(...)] attributes found in the C# services — registry scan is broken"]
    for name in sorted((cs - adapter) - EXECUTION_ONLY_TOOLS):
        errors.append(f"C# tool '{name}' has no adapter tool in server.py")
    for name in sorted(EXECUTION_ONLY_TOOLS - cs):
        errors.append(f"'{name}' is listed EXECUTION_ONLY_TOOLS but no C# [Tool] declares it")
    for name in sorted(EXECUTION_ONLY_TOOLS & adapter):
        errors.append(f"'{name}' is listed EXECUTION_ONLY_TOOLS but the adapter exposes it")
    for name in sorted(cs - contract):
        errors.append(f"C# tool '{name}' is missing from tool-schemas.json")
    unexpected = sorted((adapter - cs) - ADAPTER_ONLY_TOOLS)
    for name in unexpected:
        errors.append(f"adapter tool '{name}' has no C# handler and is not in ADAPTER_ONLY_TOOLS")
    for name in sorted(ADAPTER_ONLY_TOOLS & cs):
        errors.append(f"'{name}' is listed ADAPTER_ONLY_TOOLS but a C# handler exists")
    return errors


def test_csharp_registry_in_sync():
    """pytest entry point: C# [Tool] registry vs adapter vs contract."""
    errors = find_csharp_drift()
    assert not errors, "C#/adapter/contract drift detected:\n  - " + "\n  - ".join(errors)


def test_schema_contract_in_sync():
    """pytest entry point."""
    errors = find_drift()
    assert not errors, "MCP/contract drift detected:\n  - " + "\n  - ".join(errors)


def test_drawing_api_in_sync():
    """pytest entry point for the adapter -> drawing-package call surface."""
    errors = find_drawing_api_drift()
    assert not errors, "drawing API drift detected:\n  - " + "\n  - ".join(errors)


def test_resource_surface_in_sync():
    """pytest entry point for the resource surface."""
    errors = find_resource_drift()
    assert not errors, "MCP resource drift detected:\n  - " + "\n  - ".join(errors)


if __name__ == "__main__":
    errs = find_drift() + find_resource_drift() + find_drawing_api_drift()
    if errs:
        print("CONTRACT DRIFT DETECTED:")
        for e in errs:
            print("  -", e)
        sys.exit(1)
    counts = _adapter_tools()
    n_res = len(asyncio.run(server.mcp.list_resources()))
    n_tmpl = len(asyncio.run(server.mcp.list_resource_templates()))
    print(f"OK - {len(counts)} tools in sync (server.py <-> tool-schemas.json); "
          f"{n_res} resources + {n_tmpl} template in sync (URIs resolve, sections match "
          f"recipe-usage.md)")
    sys.exit(0)
